// Concatenate the content-script ES modules into one classic script.
//
// MV3 content_scripts cannot be ES modules in either browser, and Firefox content
// scripts cannot be relied on for dynamic import(). The alternatives were writing
// the content side as globals-based classic scripts (untestable from node, and it
// would fork the shared protocol constants) or duplicating those constants. This
// concat keeps one authoring style: everything is an ES module, unit-testable
// directly, and the build flattens it.
//
// Deliberately not a general bundler. It handles exactly the subset used here:
// static imports between the listed files, and `export` on declarations. Anything
// else fails loudly rather than silently emitting broken output.
//
// Usage: node tools/bundle-content.mjs <out.js> <in.js...>

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';

const [out, ...inputs] = process.argv.slice(2);
if (!out || inputs.length === 0) {
  console.error('usage: bundle-content.mjs <out.js> <in.js...>');
  process.exit(2);
}

// `import ... from '...'` / `import '...'`, single or multi-line.
const IMPORT_RE = /^import\s(?:[\s\S]*?\sfrom\s)?['"][^'"]+['"];?\s*$/gm;
const EXPORT_DECL_RE = /^export\s+(?=(?:default\s+)?(?:async\s+function|function|const|let|var|class))/gm;
const EXPORT_LIST_RE = /^export\s*\{[^}]*\}\s*;?\s*$/gm;

// Flattening into one scope makes a duplicated top-level name a redeclaration
// error at load time, which in a content script is silent. Caught here instead.
const DECL_RE = /^(?:async\s+function|function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

const problems = [];
const chunks = [];
const declaredIn = new Map();

for (const input of inputs) {
  const source = await readFile(input, 'utf8');

  let body = source.replace(IMPORT_RE, '');
  body = body.replace(EXPORT_LIST_RE, '');
  body = body.replace(EXPORT_DECL_RE, '');

  for (const [, name] of body.matchAll(DECL_RE)) {
    if (declaredIn.has(name)) {
      problems.push(`${input}: '${name}' already declared in ${declaredIn.get(name)}`);
    } else {
      declaredIn.set(name, input);
    }
  }

  // Anything left means a construct this tool does not understand.
  const leftover = body.match(/^\s*(?:import|export)\s/gm);
  if (leftover) {
    problems.push(`${input}: unhandled module syntax (${leftover.join(', ').trim()})`);
  }
  if (/\bexport\s+default\b/.test(body)) {
    problems.push(`${input}: default exports are not supported by this bundler`);
  }

  chunks.push(`// ---- ${input} ${'-'.repeat(Math.max(0, 60 - input.length))}\n${body.trim()}\n`);
}

if (problems.length > 0) {
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

// One IIFE so nothing leaks into the isolated world's global scope, and 'use strict'
// to match module semantics.
const bundle = `// Generated by tools/bundle-content.mjs — do not edit.
// Sources: ${inputs.join(', ')}
(() => {
'use strict';

${chunks.join('\n')}
})();
`;

await mkdir(dirname(out), { recursive: true });
await writeFile(out, bundle, 'utf8');
console.log(`  bundled ${inputs.length} modules -> ${out}`);
